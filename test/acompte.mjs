import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import { startServer } from './dev-server.mjs';
const require = createRequire('/opt/node22/lib/node_modules/');
const { chromium } = require('playwright');
const { server, port } = await startServer();
const browser = await chromium.launch({ args: ['--no-sandbox'] });
const errs = [];
try {
  const page = await (await browser.newContext({ viewport: { width: 400, height: 860 } })).newPage();
  page.on('pageerror', e => errs.push(e.message));
  await page.goto('http://127.0.0.1:' + port + '/'); await page.waitForSelector('#web-form');
  await page.fill('#w-code', 'TESTCODE'); await page.fill('#w-name', 'N'); await page.fill('#w-email', 'n@t.fr'); await page.fill('#w-pass', 'motdepasse1');
  await page.click('#web-form button'); await page.waitForSelector('nav.nav button');
  await page.evaluate(async () => {
    const db = await window.claude.use('db');
    await db.collection('dossiers').doc('d1').set({ titre: 'Mariage Test', statut: 'confirmee', dateDebut: '2026-10-20', dateFin: '2026-10-21', clientId: '', lignes: [] });
    await db.collection('documents').doc('q1').set({ type: 'devis', numero: 'D-2026-0001', statut: 'envoye', titre: 'Mariage Test', dossierId: 'd1', clientSnap: { nom: 'Martin Paul' }, societeSnap: { nom: 'Grand Ouest Locations' }, lignes: [{ designation: 'Tente 5x6', qte: 1, puHT: 200, tva: 20 }], totaux: { ht: 200, ttc: 240, detail: [{ taux: 20, montant: 40 }] }, regimeTva: 'normal', dateEmission: '2026-10-13', dateValidite: '2026-11-13', dateDebut: '2026-10-20', dateFin: '2026-10-21' });
  });
  await page.click('nav.nav button:has-text("Devis et factures")');
  await page.waitForSelector('text=D-2026-0001');
  await page.click('text=D-2026-0001');
  await page.click('[data-action="ac-add"]');
  assert.equal(await page.inputValue('#ac-montant'), '72', 'acompte suggéré 30 %');
  await page.fill('#ac-montant', '300'); await page.click('[data-action="ac-save"]');
  await page.waitForSelector('text=dépasse le reste');
  await page.fill('#ac-montant', '72'); await page.selectOption('#ac-mode', 'Carte bancaire'); await page.click('[data-action="ac-save"]');
  await page.waitForSelector('text=Reste à payer');
  assert.ok(await page.locator('.totals >> text=− 72,00').count(), 'acompte affiché');
  assert.ok(await page.locator('.totals .big:has-text("Reste à payer") >> text=168,00').count(), 'reste 168');
  await page.click('[data-action="devis-to-facture"]');
  await page.waitForSelector('text=Facture F-');
  const num = (await page.locator('.modal-h h2').innerText()).trim();
  console.log('Titre :', num);
  assert.ok(await page.locator('.totals .big:has-text("Reste à payer") >> text=168,00').count(), 'facture : reste 168');
  assert.ok(await page.locator('.totals >> text=− 72,00').count(), 'facture : acompte déduit');
  assert.equal(await page.locator('[data-action="ac-del"]').count(), 0, 'pas de suppression sur la facture');
  await page.keyboard.press('Escape');
  await page.click('nav.nav button:has-text("Tableau de bord")');
  const kpi = await page.locator('[data-t="facture"][data-st="emise"]').innerText();
  console.log('À encaisser :', kpi.replace(/\n/g, ' | '));
  assert.ok(kpi.includes('168,00'), 'tableau de bord : 168 € à encaisser');
  await page.screenshot({ path: process.argv[2] || '/tmp/acompte.png' });
  const docs = await page.evaluate(async () => (await (await fetch('/api/sync?since=0&limit=400', { credentials: 'same-origin' })).json()).docs.filter(d => d.col === 'documents').map(d => d.data.numero + ' ' + d.data.type));
  console.log('Documents :', docs.join(', '));
  assert.equal(docs.filter(x => x.endsWith('facture')).length, 1, 'une seule facture');
  assert.deepEqual(errs, []);
  console.log('Acomptes : OK');
} catch (e) { console.error('ÉCHEC', e.message.split('\n')[0], errs); process.exitCode = 1; } finally { await browser.close(); server.close(); }
